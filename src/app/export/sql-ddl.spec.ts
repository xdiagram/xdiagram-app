import { ImportError, exportDdl, guessDialect, importDdl, prepareSql, stripRecords } from "./sql-ddl";

const noSqlite = () => Promise.reject(new Error("not used"));

const PG = `
CREATE TABLE users (id bigserial PRIMARY KEY, email text NOT NULL, created_at timestamptz DEFAULT now(), active bool);
CREATE TABLE orders (id uuid PRIMARY KEY, user_id bigint NOT NULL REFERENCES users(id), total numeric(10,2));
INSERT INTO users (email) VALUES ('a@x.io');
`;

describe("SQL DDL import/export", () => {
  it("guesses the dialect", () => {
    expect(guessDialect(PG)).toBe("postgres");
    expect(guessDialect("CREATE TABLE `a` (`id` int AUTO_INCREMENT) ENGINE=InnoDB;")).toBe("mysql");
    expect(guessDialect("CREATE TABLE [dbo].[a] ([id] int IDENTITY(1,1));\nGO\n")).toBe("mssql");
    expect(guessDialect("PRAGMA foreign_keys=ON;\nCREATE TABLE a (id INTEGER PRIMARY KEY AUTOINCREMENT);")).toBe("sqlite");
    expect(guessDialect("CREATE TABLE a (id NUMBER(10), name VARCHAR2(20));")).toBe("oracle");
    expect(guessDialect("anything", "db/schema.rb")).toBe("schemarb");
  });

  it("strips what importers cannot read, keeping line numbers", () => {
    const dump = "SET x = 1;\n\\restrict abc\nCOPY public.t (a) FROM stdin;\n1\n2\n\\.\nCREATE TABLE t (a int);";
    const pg = prepareSql(dump, "postgres");
    expect(pg.text.split("\n")).toHaveLength(7);
    expect(pg.text).not.toContain("COPY");
    expect(pg.text.split("\n")[6]).toBe("CREATE TABLE t (a int);");
    expect(pg.skipped).toEqual(["COPY data ×1", "psql commands ×1"]);
    const ms = prepareSql("CREATE TABLE a (id int);\nEXEC sp_addextendedproperty 'MS_Description', 'x';\nGO", "mssql");
    expect(ms.skipped).toEqual(["EXEC ×1"]);
    expect(stripRecords('Table a {\n  id int\n}\n\nRecords a(id) {\n  1\n}\n')).toBe("Table a {\n  id int\n}\n\n");
  });

  it("imports DDL into DBML and reports errors with their line", async () => {
    const r = await importDdl(PG, "postgres", noSqlite);
    expect(r.tables).toBe(2);
    expect(r.refs).toBe(1);
    expect(r.dbml).not.toContain("Records");
    expect(r.skipped).toContain("INSERT data");
    await expect(importDdl("CREATE TABLE a (id int);\nCREATE TABLE (oops", "postgres", noSqlite)).rejects.toSatisfy(
      (e: unknown) => e instanceof ImportError && e.line === 2,
    );
  });

  it("exports DDL with types converted for the target", async () => {
    const { dbml } = await importDdl(PG, "postgres", noSqlite);
    const ms = await exportDdl(dbml, "mssql", { source: "postgres", title: "shop", origin: null, now: new Date("2026-11-13") });
    expect(ms.sql).toContain("-- SQL Server DDL for shop, generated by xdiagram on 2026-11-13");
    expect(ms.sql).toMatch(/\[created_at\] datetimeoffset/i);
    expect(ms.sql).toMatch(/\[id\] uniqueidentifier/i);
    expect(ms.sql).toMatch(/\[active\] bit/i);
    expect(ms.sql).not.toMatch(/INSERT/i);
    const same = await exportDdl(dbml, "postgres", { source: "postgres", title: "shop", origin: null });
    expect(same.sql).toMatch(/"created_at" timestamptz/i);
    expect(same.sql).not.toContain("converted");
    await expect(exportDdl("Table a {", "mysql", { source: null, title: "x", origin: null })).rejects.toThrow(/fix them/);
  });
});
